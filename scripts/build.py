#!/usr/bin/env python3
"""Build the three standalone personal themes using only Python's standard library."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "upstream.json"


def read(path):
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")


def digest(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def record_upstream(ref):
    """Record a reviewed upstream revision, refusing a locally edited base."""
    commit = subprocess.check_output(
        ["git", "rev-parse", "--verify", ref + "^{commit}"], cwd=ROOT, text=True
    ).strip()
    upstream = subprocess.check_output(
        ["git", "show", commit + ":spring.css"], cwd=ROOT
    ).decode("utf-8-sig").replace("\r\n", "\n")
    if read(ROOT / "spring.css") != upstream:
        raise ValueError("spring.css differs from the specified revision; resolve the upstream merge first.")
    metadata = {
        "repository": "https://github.com/SprInec/typora-spring-theme",
        "branch": "main",
        "commit": commit,
        "source": "spring.css",
        "sha256": digest(upstream),
    }
    MANIFEST.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8", newline="\n")


def build_themes():
    metadata = json.loads(read(MANIFEST))
    upstream = read(ROOT / "spring.css")
    if digest(upstream) != metadata["sha256"]:
        raise ValueError(
            "The upstream base changed. Review it, then run "
            "python scripts/build.py --record-upstream upstream/main. "
            "Put personal edits in styles/, not spring.css."
        )
    parts = {}
    for name in ("common", "light", "dark"):
        parts[name] = read(ROOT / "styles" / (name + ".css")).strip()
    header = (
        "/* Generated by scripts/build.py. Edit styles/*.css, not this file.\n"
        " * Upstream: SprInec/typora-spring-theme @ " + metadata["commit"] + "\n"
        " */\n\n"
        "/*\n" + read(ROOT / "LICENSE").strip() + "\n*/\n\n"
    )
    # Normalize trailing whitespace in generated output only; keep the upstream
    # source and its provenance checksum untouched.
    clean_upstream = "\n".join(line.rstrip() for line in upstream.splitlines()).rstrip()
    base = header + clean_upstream + "\n\n/* Personal shared layer */\n" + parts["common"]
    light = base + "\n\n/* Personal light layer */\n" + parts["light"] + "\n"
    dark = "\n/* Personal dark layer */\n" + parts["dark"] + "\n"
    auto_dark = "\n@media (prefers-color-scheme: dark) {\n" + "\n".join(
        "    " + line if line else "" for line in parts["dark"].splitlines()
    ) + "\n}\n"
    return {
        "spring.css": light + auto_dark,
        "spring-light.css": light,
        "spring-dark.css": light + dark,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without writing them")
    parser.add_argument("--record-upstream", metavar="REF", help="Record an exact, reviewed upstream revision")
    args = parser.parse_args()
    if args.check and args.record_upstream:
        parser.error("--check cannot update the upstream record")
    try:
        if args.record_upstream:
            record_upstream(args.record_upstream)
        generated = build_themes()
        stale = []
        for name, source in generated.items():
            target = ROOT / "dist" / name
            if args.check:
                if not target.is_file() or read(target) != source:
                    stale.append(name)
            else:
                target.parent.mkdir(exist_ok=True)
                target.write_text(source, encoding="utf-8", newline="\n")
                print("Built dist/" + name)
        if stale:
            raise ValueError("Stale generated themes: " + ", ".join(stale) + ". Run python scripts/build.py.")
        if args.check:
            print("All three generated themes are current.")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print("Build failed: " + str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
